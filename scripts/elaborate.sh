#!/usr/bin/env bash
set -euo pipefail
source "$(dirname -- "${BASH_SOURCE[0]}")/common.sh"
case ${1:-} in
  emu) mode=emu; top=core_top; output="$RTL_DIR/emu" ;;
  compare) mode=compare; top=MiniPerfTop; output="$RTL_DIR/compare/mini" ;;
  *) die "Usage: $0 emu|compare" ;;
esac
find_sbt
mkdir -p "$BUILD_DIR"
# Both elaborations share sbt's target/ directory.
exec 9>"$MINI_ROOT/.build.lock"
flock 9
properties="$MINI_ROOT/project/build.properties"
if [[ ! -f $properties ]]; then
  mkdir -p "$MINI_ROOT/project"
  printf '%s\n' '# Generated by scripts/elaborate.sh when missing.' \
    'sbt.version=2.0.2' > "$properties"
fi
key=$(fingerprint --value "$mode,$SBT" \
  "$MINI_ROOT/src/main/scala" "$MINI_ROOT/build.sbt" \
  "$properties" "$MINI_ROOT/scripts/elaborate.sh" \
  "$MINI_ROOT/scripts/common.sh")
if [[ -f "$output/$top.v" && -f "$output/.source-hash" &&
      $(<"$output/.source-hash") == "$key" ]]; then
  echo "Reusing $mode RTL: $output"
  exit 0
fi
runtime_dir="${TMPDIR:-/tmp}/miniXiangShan-sbt-${UID:-0}"
mkdir -p "$runtime_dir"
chmod 700 "$runtime_dir"
cd "$MINI_ROOT"
XDG_RUNTIME_DIR="$runtime_dir" "$SBT" --server -batch "runMain minixiangshan.CoreGen $mode"
printf '%s\n' "$key" > "$output/.source-hash"
